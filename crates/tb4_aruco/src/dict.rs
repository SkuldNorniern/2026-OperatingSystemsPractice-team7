#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Dictionary {
    pub bits: usize,
    pub codes: Vec<u64>,
    /// most bit errors corrected: random square pattern matches some code with < 2% chance
    pub max_correction: u32,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Match {
    pub id: u32,
    pub rotation: usize,
    pub hamming: u32,
}

impl Dictionary {
    pub fn new(bits: usize, codes: Vec<u64>) -> Self {
        assert!(bits * bits <= 64, "marker grid must fit in u64");
        let n = bits * bits;
        // expected codes (x4 rotations) within t bits of a random pattern
        let mut ball = 0.0;
        let mut choose = 1.0;
        let mut max_correction = 0;
        for t in 0..=n {
            if t > 0 {
                choose = choose * (n + 1 - t) as f64 / t as f64;
            }
            ball += choose;
            if 4.0 * codes.len() as f64 * ball / 2f64.powi(n as i32) > 0.02 {
                break;
            }
            max_correction = t as u32;
        }
        Self { bits, codes, max_correction }
    }

    pub fn aruco_original() -> Self {
        Self::new(5, ARUCO_ORIGINAL.iter().map(|&c| c as u64).collect())
    }

    /// OpenCV name with or without `DICT_`, any case: `ARUCO_ORIGINAL`, `4X4_50` .. `7X7_1000`,
    /// `APRILTAG_16H5`, `APRILTAG_25H9`, `APRILTAG_36H10`, `APRILTAG_36H11`
    pub fn by_name(name: &str) -> Option<Self> {
        let name = name.trim().to_ascii_uppercase();
        let name = name.strip_prefix("DICT_").unwrap_or(&name);
        if name == "ARUCO_ORIGINAL" {
            return Some(Self::aruco_original());
        }
        let &(_, bits, table, count) = crate::dict_tables::NAMED.iter().find(|d| d.0 == name)?;
        Some(Self::new(bits, table[..count].to_vec()))
    }

    /// every name `by_name` takes
    pub fn names() -> Vec<&'static str> {
        std::iter::once("ARUCO_ORIGINAL").chain(crate::dict_tables::NAMED.iter().map(|d| d.0)).collect()
    }

    pub fn len(&self) -> usize {
        self.codes.len()
    }

    pub fn is_empty(&self) -> bool {
        self.codes.is_empty()
    }

    pub fn is_white(&self, id: u32, row: usize, col: usize) -> bool {
        let n = self.bits;
        (self.codes[id as usize] >> (n * n - 1 - (row * n + col))) & 1 == 1
    }

    // Rotates the bit grid 90 degrees clockwise.
    pub fn rotate_cw(&self, code: u64) -> u64 {
        let n = self.bits;
        let mut out = 0u64;
        for r in 0..n {
            for c in 0..n {
                let src = (n - 1 - c) * n + r;
                let bit = (code >> (n * n - 1 - src)) & 1;
                out = (out << 1) | bit;
            }
        }
        out
    }

    // Returns the best id and the clockwise rotation k such that rotate_cw^k(observed) == code[id].
    // Ties at distance 0 resolve to the lowest id (as OpenCV); non-zero ties are rejected as ambiguous.
    pub fn identify(&self, observed: u64, max_hamming: u32) -> Option<Match> {
        let mut rots = [observed; 4];
        for k in 1..4 {
            rots[k] = self.rotate_cw(rots[k - 1]);
        }
        let mut best = Match {
            id: 0,
            rotation: 0,
            hamming: u32::MAX,
        };
        let mut second = u32::MAX;
        for (id, &code) in self.codes.iter().enumerate() {
            let mut dmin = u32::MAX;
            let mut kmin = 0;
            for (k, r) in rots.iter().enumerate() {
                let d = (r ^ code).count_ones();
                if d < dmin {
                    dmin = d;
                    kmin = k;
                }
            }
            if dmin < best.hamming {
                second = best.hamming;
                best = Match {
                    id: id as u32,
                    rotation: kmin,
                    hamming: dmin,
                };
            } else if dmin < second {
                second = dmin;
            }
        }
        if best.hamming > max_hamming.min(self.max_correction) || (best.hamming > 0 && second <= best.hamming) {
            return None;
        }
        Some(best)
    }
}

